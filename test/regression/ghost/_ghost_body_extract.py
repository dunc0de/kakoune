#!/usr/bin/env python3
"""Extract a detached `%sh{}` body from a Kakoune file for standalone testing.

Usage:
    python3 _ghost_body_extract.py <out> <path> <log> [command]  # emit a wrapper
    python3 _ghost_body_extract.py extract-only <path> [command] # print body

Ghost-suite copy of the llm-suite extractor (the llm original,
test/regression/llm/_llm_body_extract.py, is no longer in-tree); the ghost
defaults are the calls-log env var $GHOST_KAK_CALLS_LOG and the default command
ghost-session. The <log> argument is embedded into the generated wrapper as
GHOST_KAK_CALLS_LOG='...' so the stub can append to it without the caller
exporting anything.

Each emitted body's own ``kak_send()`` definition is replaced with a logging
stub that appends emitted commands to ``$GHOST_KAK_CALLS_LOG``. Production
bodies call ``kak -p`` which only works inside a live Kakoune session; the
stub makes emitted commands observable standalone.
"""
import sys


def extract_body(src, command):
    start = src.index(f"{command} %{{")
    sh = src.index("evaluate-commands %sh{", start) + len("evaluate-commands %sh{")
    # Brace depth tracks nested { } inside %sh{}; the opening brace after
    # evaluate-commands %sh{ is depth 1, so we walk until depth returns to 0.
    # Skip braces inside single-quoted strings and # comments to avoid
    # miscounting.
    depth, i = 1, sh
    in_single_quote = False
    in_comment = False
    while i < len(src) and depth > 0:
        c = src[i]
        if in_comment:
            if c == "\n":
                in_comment = False
        elif in_single_quote:
            if c == "'":
                in_single_quote = False
        elif c == "#":
            in_comment = True
        elif c == "'":
            in_single_quote = True
        elif not in_single_quote and not in_comment:
            if c == "{":
                depth += 1
            elif c == "}":
                depth -= 1
        i += 1
    if depth != 0:
        raise ValueError(f"unbalanced braces extracting {command} body")
    body = src[sh:i - 1]
    return body


def stub_kak_send(body):
    """Replace the body's own ``kak_send()`` definition with a logging stub that
    appends each emitted command to ``$GHOST_KAK_CALLS_LOG``.
    """
    marker = "kak_send() {"
    idx = body.find(marker)
    if idx < 0:
        return body
    brace = body.find("{", idx)
    depth, i = 0, brace
    while i < len(body) and depth >= 0:
        if body[i] == "{":
            depth += 1
        elif body[i] == "}":
            depth -= 1
            if depth == 0:
                i += 1
                break
        i += 1
    stub = 'kak_send() { printf \'%s\\n\' "$1" >> "$GHOST_KAK_CALLS_LOG"; }'
    return body[:idx] + stub + body[i:]


def main(argv):
    if len(argv) < 2:
        print("usage: _ghost_body_extract.py <out> <path> <log> [command] | "
              "extract-only <path> [command]", file=sys.stderr)
        sys.exit(2)

    if argv[1] == "extract-only":
        # extract-only mode prints the stubbed body to stdout for inline
        # inspection: extract-only <path> [command]
        path = argv[2]
        command = argv[3] if len(argv) > 3 else "ghost-session"
        with open(path) as f:
            src = f.read()
        sys.stdout.write(stub_kak_send(extract_body(src, command)))
        return

    # usage: <out> <path> <log> [command]
    out, path, log = argv[1], argv[2], argv[3]
    command = argv[4] if len(argv) > 4 else "ghost-session"
    with open(path) as f:
        src = f.read()
    body = stub_kak_send(extract_body(src, command))

    # Shell-escape the log path so quotes/backslashes in the path can't
    # corrupt the generated wrapper script.
    escaped_log = log.replace("'", "'\\''")
    # Wrapper: set the calls-log env var, then run the stubbed body directly.
    wrapper = f"#!/usr/bin/env bash\n# Auto-generated by _ghost_body_extract.py for command '{command}'.\n" \
              f"GHOST_KAK_CALLS_LOG='{escaped_log}'\n{body}"
    with open(out, "w") as f:
        f.write(wrapper)


main(sys.argv)
