#!/usr/bin/env python3
"""Extract a detached `%sh{}` body from a Kakoune file for standalone testing.

Usage:
    python3 _llm_body_extract.py <out> <path> <log> [command]   # emit a runnable wrapper
    python3 _llm_body_extract.py extract-only <path> <command>  # print the stubbed body

<out> is a path to an emitted .sh wrapper; <path> the source file; <log> the
kak_send capture log. <command> defaults to llm-tail-loop (the existing
detached-body tests). New commands (llm-session, llm-stop) pass their name so
the same brace-extraction logic reuses the anchor generically instead of a
hard-coded command string.

Each emitted body has its own ``kak_send()`` definition replaced with a logging
stub that appends emitted commands to ``$LLM_KAK_CALLS_LOG`` (the wrapper sets
that env var to <log>). Production bodies call ``kak -p`` which only works inside
a live Kakoune session; the stub makes emitted commands observable standalone.
"""
import sys


def extract_body(src, command):
    start = src.index(f"{command} %{{")
    sh = src.index("evaluate-commands %sh{", start) + len("evaluate-commands %sh{")
    # Brace depth tracks nested { } inside %sh{}; the opening brace after
    # evaluate-commands %sh{ is depth 1, so we walk until depth returns to 0.
    depth, i = 1, sh
    while i < len(src) and depth > 0:
        if src[i] == "{":
            depth += 1
        elif src[i] == "}":
            depth -= 1
        i += 1
    body = src[sh:i - 1]
    assert depth == 0, f"unbalanced braces extracting {command} body"
    return body


def stub_kak_send(body):
    """Replace the body's own ``kak_send()`` definition with a logging stub that
    appends each emitted command to ``$LLM_KAK_CALLS_LOG``.
    """
    marker = "kak_send() {"
    idx = body.find(marker)
    if idx < 0:
        return body
    brace = body.find("{", idx)
    depth, i = 0, brace
    while i < len(body) and depth >= 0:
        if body[i] == "{":
            depth += 1
        elif body[i] == "}":
            depth -= 1
            if depth == 0:
                i += 1
                break
        i += 1
    stub = 'kak_send() { printf \'%s\\n\' "$1" >> "$LLM_KAK_CALLS_LOG"; }'
    return body[:idx] + stub + body[i:]


def main(argv):
    if len(argv) < 2:
        print("usage: _llm_body_extract.py <out> <path> <log> [command] | "
              "extract-only <path> <command>", file=sys.stderr)
        sys.exit(2)

    if argv[1] == "extract-only":
        # extract-only mode prints the stubbed body to stdout for inline
        # inspection; wrapper mode below emits an executable .sh for the test harness.
        # usage: extract-only <path> [command]
        path = argv[2]
        command = argv[3] if len(argv) > 3 else "llm-tail-loop"
        with open(path) as f:
            src = f.read()
        sys.stdout.write(stub_kak_send(extract_body(src, command)))
        return

    # usage: <out> <path> <log> [command]
    out, path, log = argv[1], argv[2], argv[3]
    command = argv[4] if len(argv) > 4 else "llm-tail-loop"
    with open(path) as f:
        src = f.read()
    body = stub_kak_send(extract_body(src, command))

    # Wrapper: set the calls-log env var, then run the stubbed body directly.
    wrapper = f"#!/usr/bin/env bash\n# Auto-generated by _llm_body_extract.py for command '{command}'.\n" \
              f"LLM_KAK_CALLS_LOG='{log}'\n{body}"
    with open(out, "w") as f:
        f.write(wrapper)


main(sys.argv)
